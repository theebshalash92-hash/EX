const currentUser = sessionStorage.getItem('currentUser');
const currentDept = sessionStorage.getItem('currentDept');

if (!currentUser || !currentDept) {
    window.location.href = 'index.html';
}

document.getElementById('displayUser').innerText = currentUser;
document.getElementById('displayDept').innerText = currentDept;

function logout() {
    sessionStorage.clear();
    window.location.href = 'index.html';
}

let inventory = JSON.parse(localStorage.getItem('inventory')) || [];

const form = document.getElementById('itemForm');
const tableBody = document.getElementById('itemTableBody');

function checkExpiryStatus(expiryDateStr) {
    const today = new Date();
    const expiryDate = new Date(expiryDateStr);
    const diffTime = expiryDate - today;
    const diffDays = Math.ceil(diffTime / (1000 * 60 * 60 * 24));

    if (diffDays < 0) {
        return `<span class="bg-red-100 text-red-800 text-xs px-2 py-1 rounded font-bold">منتهية الصلاحية</span>`;
    } else if (diffDays <= 30) {
        return `<span class="bg-yellow-100 text-yellow-800 text-xs px-2 py-1 rounded font-bold">قريب الانتهاء (${diffDays} يوم)</span>`;
    } else {
        return `<span class="bg-green-100 text-green-800 text-xs px-2 py-1 rounded">سارية المفعول</span>`;
    }
}

function renderInventory() {
    tableBody.innerHTML = '';
    
    const deptInventory = inventory.filter(item => item.department === currentDept);

    if (deptInventory.length === 0) {
        tableBody.innerHTML = `<tr><td colspan="6" class="text-center p-4 text-gray-500">لا توجد مواد مسجلة في هذا القسم حالياً</td></tr>`;
        return;
    }

    deptInventory.forEach((item, index) => {
        const statusBadge = checkExpiryStatus(item.expiryDate);
        const globalIndex = inventory.findIndex(inv => inv === item);
        
        const row = document.createElement('tr');
        row.innerHTML = `
            <td class="p-3 text-gray-800 font-medium">${item.name}</td>
            <td class="p-3 text-blue-700 font-semibold"><span class="bg-blue-50 border border-blue-200 px-2 py-1 rounded text-xs">${item.location}</span></td>
            <td class="p-3 text-gray-700 font-bold">${item.quantity}</td>
            <td class="p-3 text-gray-600">${item.expiryDate}</td>
            <td class="p-3">${statusBadge}</td>
            <td class="p-3">
                <button onclick="deleteItem(${globalIndex})" class="text-red-600 hover:text-red-800 text-sm">حذف</button>
            </td>
        `;
        tableBody.appendChild(row);
    });
}

form.addEventListener('submit', function(e) {
    e.preventDefault();
    
    const name = document.getElementById('itemName').value;
    const location = document.getElementById('itemLocation').value;
    const quantity = parseInt(document.getElementById('itemQuantity').value);
    const expiryDate = document.getElementById('itemExpiryDate').value;

    inventory.push({ name, location, department: currentDept, quantity, expiryDate });
    localStorage.setItem('inventory', JSON.stringify(inventory));

    form.reset();
    renderInventory();
});

function deleteItem(index) {
    inventory.splice(index, 1);
    localStorage.setItem('inventory', JSON.stringify(inventory));
    renderInventory();
}

function exportPDF() {
    const { jsPDF } = window.jspdf;
    const doc = new jsPDF();

    doc.setFont("helvetica", "bold");
    doc.setFontSize(18);
    doc.text(`Inventory Report - ${currentDept}`, 14, 20);

    doc.setFontSize(12);
    doc.text(`Generated by: ${currentUser} | Date: ${new Date().toLocaleDateString()}`, 14, 28);

    const deptInventory = inventory.filter(item => item.department === currentDept);
    
    if (deptInventory.length === 0) {
        alert("لا توجد بيانات لتصديرها في هذا القسم!");
        return;
    }

    const tableData = deptInventory.map((item, i) => [
        i + 1,
        item.name,
        item.location,
        item.quantity,
        item.expiryDate
    ]);

    doc.autoTable({
        startY: 35,
        head: [['#', 'Item Name', 'Location', 'Quantity', 'Expiry Date']],
        body: tableData,
        theme: 'grid',
        headStyles: { fillColor: [41, 128, 185] }
    });

    doc.save(`${currentDept}-Inventory-Report.pdf`);
}

renderInventory();
